    /// Fused SIMD‐batch routine: for four TEPs at once, compute both `log_pe` and `p_pro`.
    ///
    /// Internally, this does exactly what
    ///   let log_pe_4 = calculate_log_pe_4(teps);
    ///   let p_pro_4 = calculate_p_pro_4(teps, &log_pe_4);
    /// would do—but in one combined pass, reducing overhead and ensuring that both lanes stay in cache.
    ///
    /// Returns a tuple `( [log_pe_0, log_pe_1, log_pe_2, log_pe_3],
    ///                    [p_pro_0, p_pro_1, p_pro_2, p_pro_3] )`.
    #[inline(always)]
    fn calculate_log_pe_and_p_pro_4(&self, teps: [&TestErrorPattern; 4]) -> ([f32; 4], [f32; 4]) {
        // 1) Step 1: compute `log_pe_4` exactly as calculate_log_pe_4(teps) does:
        // Initialize from sum_log_1_minus_p
        let mut log_pe_vals = [self.sum_log_1_minus_p; 4];
        {
            // Each TEP has at most 8 positions; for j in 0..8, adjust lanes
            for j in 0..8 {
                unsafe {
                    let pos0 = teps[0].positions()[j] as usize;
                    let pos1 = teps[1].positions()[j] as usize;
                    let pos2 = teps[2].positions()[j] as usize;
                    let pos3 = teps[3].positions()[j] as usize;
                    let mask0 = (j < teps[0].num_positions() as usize) as u8 as f32;
                    let mask1 = (j < teps[1].num_positions() as usize) as u8 as f32;
                    let mask2 = (j < teps[2].num_positions() as usize) as u8 as f32;
                    let mask3 = (j < teps[3].num_positions() as usize) as u8 as f32;

                    let lp0 = *self.log_p.get_unchecked(pos0);
                    let lp1 = *self.log_p.get_unchecked(pos1);
                    let lp2 = *self.log_p.get_unchecked(pos2);
                    let lp3 = *self.log_p.get_unchecked(pos3);
                    let l1mp0 = *self.log_1_minus_p.get_unchecked(pos0);
                    let l1mp1 = *self.log_1_minus_p.get_unchecked(pos1);
                    let l1mp2 = *self.log_1_minus_p.get_unchecked(pos2);
                    let l1mp3 = *self.log_1_minus_p.get_unchecked(pos3);

                    // For each lane i, do: log_pe_vals[i] += (log_p[pos_i] - log_1_minus_p[pos_i]) * mask_i
                    log_pe_vals[0] += (lp0 - l1mp0) * mask0;
                    log_pe_vals[1] += (lp1 - l1mp1) * mask1;
                    log_pe_vals[2] += (lp2 - l1mp2) * mask2;
                    log_pe_vals[3] += (lp3 - l1mp3) * mask3;
                }
            }
        }

        // 2) Step 2: compute `p_pro_4` similarly to calculate_p_pro_4, but re-use log_pe_vals:
        //
        //    pe[i] = exp(log_pe_vals[i])
        //    debw[i] = calculate_debw(teps[i])
        //    then form q_args, pass through q_function_4x, combine into p_pro[i].
        //
        // Load `log_pe_vals` and compute pe_arr = exp(log_pe_vals):
        let pe_arr = Self::exp4(&log_pe_vals);

        // Compute deBW for each of the four TEPs in one shot:
        let debw_arr: [f32; 4] = self.calculate_debw_4(teps);

        if self.promising_probability_model == PromisingProbabilityModel::WeightedNormal {
            let mut p_pro_out = [0.0f32; 4];
            for i in 0..4 {
                p_pro_out[i] = self.calculate_weighted_normal_p_pro(pe_arr[i], debw_arr[i]);
            }
            return (log_pe_vals, p_pro_out);
        }

        // Constants for parity‐part average p and n_minus_k:
        let p = self.parity_p_avg;
        let nmk_f = self.nmk as f32;

        // We will build arrays q_arg1[4], q_arg2[4], one lane at a time:
        let mut q_arg1 = [0.0_f32; 4];
        let mut q_arg2 = [0.0_f32; 4];
        let denom1 = (nmk_f * p * (1.0_f32 - p)).sqrt(); // sqrt(N * p * (1-p))
        let denom2 = nmk_f.sqrt(); // sqrt(N)

        for i in 0..4 {
            // Compute β_i = clamp( (d_min_w - debw_i) / e_p_alpha, 0..nmk_f )
            let beta_i = ((self.d_min_w - debw_arr[i]) / self.e_p_alpha)
                .min(nmk_f)
                .max(0.0_f32);

            // q_arg1[i] = (β_i + 0.5 - N*p) / sqrt(N*p*(1-p))
            let mean1 = nmk_f * p;
            q_arg1[i] = (beta_i + 0.5_f32 - mean1) / denom1;

            // q_arg2[i] = (2*β_i + 1 - N) / sqrt(N)
            q_arg2[i] = (2.0_f32 * beta_i + 1.0_f32 - nmk_f) / denom2;
        }

        // Evaluate both normal-tail arguments in four lanes.
        let (q1_arr, q2_arr) = Self::q_function_pair_4x(&q_arg1, &q_arg2);

        // Finally compute `p_pro[i] = pe[i]*(1 - q1_arr[i]) + (1 - pe[i])*(1 - q2_arr[i])`, clamped to [0,1].
        let mut p_pro_out = [0.0_f32; 4];
        for i in 0..4 {
            let pei = pe_arr[i];
            let one_minus_q1 = 1.0_f32 - q1_arr[i];
            let one_minus_q2 = 1.0_f32 - q2_arr[i];
            let term1 = pei * one_minus_q1;
            let term2 = (1.0_f32 - pei) * one_minus_q2;
            // Final clamp (in case floating‐point makes it slightly <0 or >1):
            let val = (term1 + term2).clamp(0.0_f32, 1.0_f32);
            p_pro_out[i] = val;
        }

        (log_pe_vals, p_pro_out)
    }

    /// Calculates the Promising Probability (P_pro) using the Normal approximation
    /// of the PB-OSD paper's Equation 8 (Yue et al., 2021).
    ///
    /// P_pro is the probability that the current Test Error Pattern (TEP) `e`
    /// could lead to a codeword estimate better than the current best, considering
    /// potential errors in the parity part. It is used as a pruning criterion (DC).
    ///
    /// # Paper Reference: Equation 8
    ///
    /// P_e^{pro} = Σ_{j=0..β} [ binom(n-k, j) * ( P(e) * p^j * (1-p)^(n-k-j) + (1 - P(e)) * 2^(k-n) ) ]
    ///
    /// where:
    ///   - `n`: Codeword length (174)
    ///   - `k`: Message length (91 - num_cascaded_bits)
    ///   - `e`: The specific TEP being evaluated (errors in the first k bits).
    ///   - `P(e)`: The a priori probability of TEP `e` occurring (calculated by `calculate_log_pe`).
    ///   - `p`: Average error probability of a parity bit (`self.parity_p_avg`).
    ///   - `β`: Maximum number of parity errors allowed for the TEP `e` to potentially
    ///     yield a better codeword than the current best (`d_min_w`).
    ///     β = floor( (d_min_w - d_{e,B}^{(W)}) / E_P[α] ).max(0).min(n-k)
    ///     where d_{e,B}^{(W)} is the WHD of the TEP in the message part, and E_P[α]
    ///     is the average reliability of parity bits.
    ///   - `binom(n-k, j)`: Binomial coefficient "n-k choose j".
    ///
    /// # Derivation of the Normal Approximation
    ///
    /// Let `N = n - k`. We can rewrite Eq. 8 by splitting the summation:
    ///
    /// P_e^{pro} = P(e) * [ Σ_{j=0..β} binom(N, j) * p^j * (1-p)^(N-j) ]
    ///           + (1 - P(e)) * 2^(k-n) * [ Σ_{j=0..β} binom(N, j) ]
    ///
    /// Let's analyze the two summation terms:
    ///
    /// 1.  **First Sum (S1):** `Σ_{j=0..β} binom(N, j) * p^j * (1-p)^(N-j)`
    ///     This is the Cumulative Distribution Function (CDF) of a Binomial random variable
    ///     `X ~ Binomial(N, p)`, evaluated at `β`.
    ///     `S1 = Pr(X <= β)`
    ///
    /// 2.  **Second Sum (S2):** `Σ_{j=0..β} binom(N, j)`
    ///     Consider a Binomial random variable `Y ~ Binomial(N, 0.5)`. Its Probability Mass
    ///     Function (PMF) is `Pr(Y=j) = binom(N, j) * (0.5)^j * (0.5)^(N-j) = binom(N, j) * (0.5)^N`.
    ///     Therefore, `binom(N, j) = Pr(Y=j) * 2^N`.
    ///     Substituting this into S2:
    ///     `S2 = Σ_{j=0..β} [ Pr(Y=j) * 2^N ] = 2^N * Σ_{j=0..β} Pr(Y=j) = 2^N * Pr(Y <= β)`
    ///
    /// Substituting S1 and S2 into the `P_e^{pro}` equation gives:
    ///
    /// P_e^{pro} = P(e) * Pr(X <= β) + (1 - P(e)) * 2^(k-n) * [ 2^N * Pr(Y <= β) ]
    /// P_e^{pro} = P(e) * Pr(X <= β) + (1 - P(e)) * 2^(k-n+N) * Pr(Y <= β)
    ///
    /// Since `N = n - k`, the exponent `k-n+N = k-n+(n-k) = 0`. So, `2^(k-n+N) = 2^0 = 1`.
    ///
    /// P_e^{pro} = P(e) * Pr(X <= β) + (1 - P(e)) * Pr(Y <= β)
    ///
    /// **The `2^(k-n)` factor cancels out during this derivation.**
    ///
    /// Approximate the Binomial CDFs `Pr(X <= β)` and `Pr(Y <= β)` using the
    /// De Moivre-Laplace theorem (Normal approximation) with continuity correction (+0.5):
    ///
    /// - For `X ~ Binomial(N, p)`: Mean = `N*p`, Variance = `N*p*(1-p)`
    ///   `Pr(X <= β) ≈ Phi( (β + 0.5 - N*p) / sqrt(N*p*(1-p)) )`
    ///
    /// - For `Y ~ Binomial(N, 0.5)`: Mean = `N*0.5`, Variance = `N*0.25`
    ///   `Pr(Y <= β) ≈ Phi( (β + 0.5 - N*0.5) / sqrt(N*0.25) )`
    ///   `= Phi( (2*β + 1 - N) / sqrt(N) )`
    ///
    /// Using the Q-function relationship `Phi(x) = 1 - Q(x)`:
    ///
    /// - `Pr(X <= β) ≈ 1 - Q( arg1 )` where `arg1 = (β + 0.5 - N*p) / sqrt(N*p*(1-p))`
    /// - `Pr(Y <= β) ≈ 1 - Q( arg2 )` where `arg2 = (2*β + 1 - N) / sqrt(N)`
    ///
    /// Substituting these approximations back gives the final formula implemented:
    ///
    /// P_e^{pro} ≈ P(e) * (1 - Q(arg1)) + (1 - P(e)) * (1 - Q(arg2))
    ///
    /// This function computes this value using a fast approximation for the Q-function.
    ///
    /// # Arguments
    /// * `tep` - The Test Error Pattern being evaluated. `tep.log_pe_value()` must be pre-calculated.
    ///
    /// # Returns
    /// The approximated Promising Probability (P_pro) clamped between 0.0 and 1.0.
    #[inline]
    fn weighted_normal_cdf(budget: f32, mean: f32, variance: f32, alpha_sum: f32) -> f32 {
        if budget < 0.0 {
            0.0
        } else if budget >= alpha_sum {
            1.0
        } else if variance <= f32::EPSILON {
            if budget >= mean {
                1.0
            } else {
                0.0
            }
        } else {
            (1.0 - q_function((budget - mean) / variance.sqrt())).clamp(0.0, 1.0)
        }
    }

    #[inline]
    fn calculate_weighted_normal_p_pro(&self, pe: f32, debw: f32) -> f32 {
        let moments = self
            .weighted_normal_moments
            .expect("weighted-normal moments must be initialized when the model is selected");
        let budget = self.d_min_w - debw;
        let conditional_cdf = Self::weighted_normal_cdf(
            budget,
            moments.error_mean,
            moments.error_variance,
            moments.alpha_sum,
        );
        let uniform_cdf = Self::weighted_normal_cdf(
            budget,
            moments.uniform_mean,
            moments.uniform_variance,
            moments.alpha_sum,
        );
        (pe * conditional_cdf + (1.0 - pe) * uniform_cdf).clamp(0.0, 1.0)
    }

    fn calculate_p_pro(&self, tep: &TestErrorPattern) -> f32 {
        // Calculate Ppro ≈ P(e) * S1 + (1 - P(e)) * S2_term
        // where S1 ≈ Phi(arg1_complement) and S2_term ≈ 2^k * Phi(arg2_complement)
        // Phi(x) = 1 - Q(x)
        let log_pe = tep.log_pe_value();

        // Calculate P(e) carefully, avoiding exp(-large_neg_num) if log_pe is very small
        let pe = if log_pe < -80.0 { 0.0 } else { log_pe.exp() }; // Avoid underflow/NaN

        let debw: f32 = self.calculate_debw(tep);

        if self.promising_probability_model == PromisingProbabilityModel::WeightedNormal {
            return self.calculate_weighted_normal_p_pro(pe, debw);
        }

        let p: f32 = self.parity_p_avg; // Assumed 0 < p < 1
        let n_minus_k = self.nmk; // N = n - k (Assumed > 0)
        let n_minus_k_f: f32 = n_minus_k as f32; // N as float

        // Calculate threshold β (float) and clamp to the valid range [0, N].
        // Clamping is kept as the calculation might exceed N or be < 0 depending on inputs.
        let beta_float = ((self.d_min_w - debw) / self.e_p_alpha)
            .min(n_minus_k_f) // Clamp upper bound to N
            .max(0.0); // Clamp lower bound to 0

        // --- Calculate Q-function arguments ---
        // Calculate arg1 components
        let mean1 = n_minus_k_f * p;
        let variance1 = mean1 * (1.0_f32 - p); // N*p*(1-p). Since p is not 0 or 1, and N>0, variance1 > 0.
        let std_dev1 = variance1.sqrt(); // Safe due to variance1 > 0
        let q_arg_1 = (beta_float + 0.5_f32 - mean1) / std_dev1;

        // Calculate arg2 components
        // Denominator comes from simplifying the Z-score argument for Binomial(N, 0.5)
        // (Value+0.5-Mean)/StdDev = (beta+0.5-N/2)/(sqrt(N)/2) = (2*beta+1-N)/sqrt(N)
        let std_dev2_denom = n_minus_k_f.sqrt(); // sqrt(N). Safe since N > 0.
        let q_arg_2 = (2.0_f32 * beta_float + 1.0_f32 - n_minus_k_f) / std_dev2_denom;

        // --- Calculate Q-functions using the provided approximation ---
        let q1 = q_function(q_arg_1);
        let q2 = q_function(q_arg_2);

        // --- Final P_pro approximation ---
        // P_pro ≈ P(e) * (1 - Q(arg1)) + (1 - P(e)) * (1 - Q(arg2))
        // Note: 1-q1 or 1-q2 might be negative if q_function > 1.0
        let term1 = pe * (1.0_f32 - q1);
        let term2 = (1.0_f32 - pe) * (1.0_f32 - q2);
        let p_pro = term1 + term2;

        p_pro.clamp(0.0, 1.0)
    }

    #[inline]
    fn calculate_p_pro_4(&self, teps: [&TestErrorPattern; 4], log_pe_vals: &[f32; 4]) -> [f32; 4] {
        let mut out = [0.0; 4];

        // 1) Compute pe[i] = exp(log_pe_vals[i])
        let pe_arr = Self::exp4(log_pe_vals);

        // 2) Compute d_eBW for each TEP in a 4-wide manner
        let debw_arr = self.calculate_debw_4(teps);

        if self.promising_probability_model == PromisingProbabilityModel::WeightedNormal {
            for i in 0..4 {
                out[i] = self.calculate_weighted_normal_p_pro(pe_arr[i], debw_arr[i]);
            }
            return out;
        }

        // Shared constants
        let p = self.parity_p_avg;
        let nmk_f = self.nmk as f32;

        let mut q_arg1 = [0.0; 4];
        let mut q_arg2 = [0.0; 4];

        for i in 0..4 {
            let debw_i = debw_arr[i];
            let beta_i = ((self.d_min_w - debw_i) / self.e_p_alpha)
                .min(nmk_f)
                .max(0.0);

            let denom1 = (nmk_f * p * (1.0 - p)).sqrt(); // scalar
            let denom2 = nmk_f.sqrt(); // scalar

            q_arg1[i] = (beta_i + 0.5 - nmk_f * p) / denom1;
            q_arg2[i] = (2.0 * beta_i + 1.0 - nmk_f) / denom2;
        }

        let q1_arr = q_function_4x(&q_arg1);
        let q2_arr = q_function_4x(&q_arg2);

        for i in 0..4 {
            let pei = pe_arr[i];
            let q1 = q1_arr[i];
            let q2 = q2_arr[i];
            out[i] = pei * (1.0 - q1) + (1.0 - pei) * (1.0 - q2);
        }

        out
    }

    fn calculate_p_pro_original(&self, tep: &TestErrorPattern) -> f32 {
        // Note this function is probably using the wrong equation - so it's likely wrong.
        let pe: f32 = tep.log_pe_value().exp();
        let debw: f32 = self.calculate_debw(tep);

        let p: f32 = self.parity_p_avg;
        let n_minus_k = self.nmk;
        let n_minus_k_f: f32 = n_minus_k as f32;

        // Mean and standard deviation for normal approximation
        let mean: f32 = n_minus_k_f * p;
        let var: f32 = n_minus_k_f * p * (1.0 - p);

        // Standardized argument for Q-function
        let beta = ((self.d_min_w - debw) / self.e_p_alpha)
            .min(n_minus_k_f)
            .max(0.0);

        let std_dev_recip = var.sqrt().recip();
        let x = (beta - mean) * std_dev_recip;

        // Compute approximation using Q-function
        let q_val = q_function(x);
        let log_1_minus_pe: f32 = (1_f32 - pe).ln();
        pe * (1.0 - q_val) + (log_1_minus_pe + self.log_two_pow_nmk).exp()
    }

    // Calculate d_e = c_e XOR y_mrb
    #[inline(always)]
    pub fn calculate_d_e(&self, cw: &[bool; 174]) -> [bool; 174] {
        let mut result = [false; 174];
        result
            .iter_mut()
            .zip(cw.iter().zip(self.c0_mrb.iter()))
            .for_each(|(r, (&a, &b))| *r = a != b);
        result
    }

    /// Checks if a codeword satisfies all parity equations.
    ///
    /// Uses the generator matrix in systematic form to verify that each parity bit
    /// matches the value obtained by encoding the message bits.
    #[inline(always)]
