/// Counterfactual calibration trace collected while probability pruning is disabled.
#[derive(Debug, Clone, PartialEq)]
#[non_exhaustive]
pub struct CalibrationTrace {
    /// Probability intervals and their accumulated observations.
    pub bins: [CalibrationBin; 12],
    /// Total predictions recorded.
    pub observations: u64,
    /// Total candidates that improved the incumbent.
    pub improvements: u64,
    /// Total squared prediction error.
    pub brier_sum: f64,
}

impl CalibrationTrace {
    fn new() -> Self {
        let bounds = [
            (0.0, 0.0),
            (0.0, 1e-12),
            (1e-12, 1e-10),
            (1e-10, 1e-8),
            (1e-8, 1e-6),
            (1e-6, 1e-5),
            (1e-5, 1e-4),
            (1e-4, 1e-3),
            (1e-3, 1e-2),
            (1e-2, 1e-1),
            (1e-1, 5e-1),
            (5e-1, 1.0),
        ];
        Self {
            bins: std::array::from_fn(|index| {
                CalibrationBin::new(bounds[index].0, bounds[index].1)
            }),
            observations: 0,
            improvements: 0,
            brier_sum: 0.0,
        }
    }

    fn record(
        &mut self,
        predicted: f32,
        incumbent_distance: f32,
        message_distance: f32,
        candidate_distance: f32,
        improved: bool,
        order: u8,
        search_position: u32,
    ) {
        let predicted = predicted.clamp(0.0, 1.0);
        let index = if predicted == 0.0 {
            0
        } else {
            self.bins
                .iter()
                .position(|bin| predicted <= bin.upper_probability)
                .unwrap_or(self.bins.len() - 1)
        };
        let target = f64::from(improved);
        let error = predicted as f64 - target;
        let bin = &mut self.bins[index];
        bin.observations += 1;
        bin.improvements += u64::from(improved);
        bin.predicted_sum += predicted as f64;
        bin.brier_sum += error * error;
        if incumbent_distance.is_finite() {
            bin.incumbent_distance_sum += incumbent_distance as f64;
            bin.finite_incumbents += 1;
        }
        bin.message_distance_sum += message_distance as f64;
        bin.candidate_distance_sum += candidate_distance as f64;
        bin.search_position_sum += search_position as u64;
        bin.order_sum += order as u64;
        self.observations += 1;
        self.improvements += u64::from(improved);
        self.brier_sum += error * error;
    }
}

#[derive(Debug, Clone, Copy)]
struct ProbabilityQueueEntry(TestErrorPattern);

impl ProbabilityQueueEntry {
    fn canonical_cmp(a: &TestErrorPattern, b: &TestErrorPattern) -> Ordering {
        a.positions()[..a.num_positions() as usize]
            .cmp(&b.positions()[..b.num_positions() as usize])
    }
}

impl PartialEq for ProbabilityQueueEntry {
    fn eq(&self, other: &Self) -> bool {
        self.cmp(other) == Ordering::Equal
    }
}

impl Eq for ProbabilityQueueEntry {}

impl PartialOrd for ProbabilityQueueEntry {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for ProbabilityQueueEntry {
    fn cmp(&self, other: &Self) -> Ordering {
        self.0
            .log_pe_value()
            .total_cmp(&other.0.log_pe_value())
            .then_with(|| other.0.num_positions().cmp(&self.0.num_positions()))
            .then_with(|| Self::canonical_cmp(&other.0, &self.0))
    }
}

