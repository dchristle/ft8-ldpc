    /// Evaluates up to ten iterator patterns, discards their scores, then calls `decode`.
    pub fn decode_with_modular_components(&mut self) -> FrameResult {
        self.initialize_structured_components();

        let mut _best_tep: Option<TestErrorPattern> = None;
        let mut best_prob = f32::NEG_INFINITY;

        for _ in 0..10 {
            if let Some(tep) = self.tep_iterator().next() {
                let log_prob = self.calculate_probability_with_new_module(&tep);
                if log_prob > best_prob {
                    best_prob = log_prob;
                    _best_tep = Some(tep);
                }
            } else {
                break;
            }
        }

        self.decode()
    }

