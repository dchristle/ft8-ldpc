    #[test]
    fn binomial_matches_pascal_triangle_for_representable_coefficients() {
        let mut row = [0u128; 93];
        row[0] = 1;
        for n in 0..=91 {
            for k in 0..=n {
                if let Ok(expected) = u32::try_from(row[k]) {
                    assert_eq!(binomial(n as u32, k as u32), expected, "n={n}, k={k}");
                }
            }
            assert_eq!(binomial(n as u32, n as u32 + 1), 0);
            for k in (1..=n + 1).rev() {
                row[k] += row[k - 1];
            }
        }
    }

    #[test]
    fn poisson_binomial_cdf_uses_individual_probabilities() {
        let probabilities = [0.1, 0.2, 0.3, 0.4];
        let mut expected = 0.0f32;
        for mask in 0u32..(1 << probabilities.len()) {
            if mask.count_ones() > 1 {
                continue;
            }
            let mut probability = 1.0f32;
            for (index, &p) in probabilities.iter().enumerate() {
                probability *= if mask & (1 << index) != 0 { p } else { 1.0 - p };
            }
            expected += probability;
        }

        let actual = FrameDecoder::poisson_binomial_cdf_at_most(&probabilities, 1);
        assert!((actual - expected).abs() < 1e-6);
    }

    #[test]
    fn batch_q_function_handles_negative_arguments() {
        let negative = [-9.0, -5.0, -2.0, -0.5];
        let positive = [0.0, 0.5, 2.0, 5.0];
        let (actual_negative, actual_positive) =
            FrameDecoder::q_function_pair_4x(&negative, &positive);

        for lane in 0..4 {
            let expected_negative = crate::pb_osd::probability::q_function(negative[lane]);
            let expected_positive = crate::pb_osd::probability::q_function(positive[lane]);
            assert!((actual_negative[lane] - expected_negative).abs() < 1e-6);
            assert!((actual_positive[lane] - expected_positive).abs() < 1e-6);
        }
    }
