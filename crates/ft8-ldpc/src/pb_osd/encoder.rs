    // Calculate the success probability, given a TEP, using the approximation in
    // equation 3
    fn calculate_p_suc_e(&self, tep: &TestErrorPattern, cw: &[bool; 174]) -> f32 {
        // Calculate d_e (the difference vector) with the hard decision codeword
        let d_e = self.calculate_d_e(cw);
        let log_pe = tep.log_pe_value();
        let pe = log_pe.exp();
        assert!(pe.is_finite(), "exp(log_pe) is not finite: {pe}");

        assert!(pe < (1_f32 + 1e-5), "p_e too large!");
        // Avoid issues when P(e) is extremely close to 1.
        if (1.0 - pe).abs() < 1e-10 {
            // println!("Returning 1.0 to avoid numerical issues in p_suc_e");
            return 1.0;
        }

        // Calculate log(Pr(d_{e,P})) = Sum_{i=k..n-1} [log(P(i)) if d_{e,i}=1 else log(1-P(i))]
        // Note: d_e is full length N, but we only sum over parity part k..N-1
        let mut log_pi_product = 0.0;
        for i in (self.k as usize)..N {
            // d_e[i] corresponds to the difference in the i-th position (parity part)
            let d_e_i_is_one = d_e[i];

            // Select log(P(i)) or log(1-P(i)) based on d_e[i]
            // SAFETY: Assumes log_p and log_1_minus_p contain valid finite numbers
            let log_prob = if d_e_i_is_one {
                unsafe { *self.log_p.get_unchecked(i) }
            } else {
                unsafe { *self.log_1_minus_p.get_unchecked(i) }
            };

            assert!(
                log_prob.is_finite(),
                "log_prob for i={i} is not finite: {log_prob}"
            );
            log_pi_product += log_prob;
        }

        assert!(
            log_pi_product.is_finite(),
            "log_pi_product is not finite: {log_pi_product}"
        );

        // Calculate log((1-P(e))/P(e)) stably
        let stable_log_ratio = (-pe).ln_1p() - log_pe;
        assert!(
            stable_log_ratio.is_finite(),
            "stable_log_ratio is not finite: {stable_log_ratio}"
        );

        // Calculate log(2^(k-n)) = -log(2^(n-k)) using precomputed value
        let log_2_pow_k_minus_n = -self.log_two_pow_nmk; // ln(2^(k-n))
        assert!(
            log_2_pow_k_minus_n.is_finite(),
            "log_2_pow_k_minus_n is not finite: {log_2_pow_k_minus_n}"
        );

        // Calculate log(X) = log [ ( (1-P(e)) * 2^(k-n) ) / ( P(e) * Pr(d_{e,P}) ) ]
        // log(X) = log(1-P(e)) - log(P(e)) + log(2^(k-n)) - log(Pr(d_{e,P}))
        let diff = stable_log_ratio + log_2_pow_k_minus_n - log_pi_product;
        assert!(
            diff.is_finite(),
            "Logarithm of ratio 'diff' is not finite: {diff}"
        );

        // Calculate final probability P_suc = 1.0 / (1.0 + X) = 1.0 / (1.0 + exp(log(X)))
        let p_suc_e = 1.0 / (1.0 + diff.exp());
        assert!(
            p_suc_e.is_finite(),
            "Final p_suc_e is NaN or infinite: {p_suc_e}"
        );

        // Clamp result to [0, 1] range just in case of minor floating point inaccuracies
        p_suc_e.clamp(0.0, 1.0)
    }

    #[inline]
    fn calculate_p_suc_if_enabled(&self, tep: &TestErrorPattern, cw: &[bool; 174]) -> Option<f32> {
        self.p_suc_t
            .is_finite()
            .then(|| self.calculate_p_suc_e(tep, cw))
    }

    /// Process 4 TEPs in a fully fused SIMD pipeline
    /// Returns (valid_mask, distances, codewords, should_process_children)
    #[inline(never)]
    pub fn process_tep_batch_fused(
        &self,
        teps: [&TestErrorPattern; 4],
        valid_count: usize,
        num_teps_processed: u32,
    ) -> ([bool; 4], [f32; 4], [[u64; 3]; 4], [bool; 4]) {
        if self.p_pro_t <= 0.0 {
            let mut should_process = [false; 4];
            let mut codewords = [self.baseline_codeword; 4];
            for i in 0..valid_count {
                should_process[i] = true;
                codewords[i] = self.generate_codeword_v2(teps[i]);
            }
            let distances = self.batch_weighted_hamming_f32(&codewords, &should_process);
            return (should_process, distances, codewords, should_process);
        }

        // Cache slice references to eliminate repeated field access overhead
        let log_p = &self.log_p;
        let log_1_minus_p = &self.log_1_minus_p;
        let alpha_mrb = &self.alpha_mrb;

        let mut log_pe_vals = [self.sum_log_1_minus_p; 4];
        let mut debw_vals = [0.0f32; 4];

        // Precompute num_positions to avoid repeated comparisons
        let num_pos = [
            teps[0].num_positions() as usize,
            teps[1].num_positions() as usize,
            teps[2].num_positions() as usize,
            teps[3].num_positions() as usize,
        ];

        // Fully interleaved processing for minimal register pressure
        // Each TEP is processed completely before moving to the next
        for j in 0..8 {
            unsafe {
                // TEP 0: load->compute->accumulate immediately
                let pos = teps[0].positions()[j] as usize;
                let mask = (j < num_pos[0]) as u8 as f32;
                let lp = *log_p.get_unchecked(pos);
                let l1mp = *log_1_minus_p.get_unchecked(pos);
                let alpha = *alpha_mrb.get_unchecked(pos);
                log_pe_vals[0] += (lp - l1mp) * mask;
                debw_vals[0] += alpha * mask;

                // TEP 1: reuse same variable names (register reuse)
                let pos = teps[1].positions()[j] as usize;
                let mask = (j < num_pos[1]) as u8 as f32;
                let lp = *log_p.get_unchecked(pos);
                let l1mp = *log_1_minus_p.get_unchecked(pos);
                let alpha = *alpha_mrb.get_unchecked(pos);
                log_pe_vals[1] += (lp - l1mp) * mask;
                debw_vals[1] += alpha * mask;

                // TEP 2
                let pos = teps[2].positions()[j] as usize;
                let mask = (j < num_pos[2]) as u8 as f32;
                let lp = *log_p.get_unchecked(pos);
                let l1mp = *log_1_minus_p.get_unchecked(pos);
                let alpha = *alpha_mrb.get_unchecked(pos);
                log_pe_vals[2] += (lp - l1mp) * mask;
                debw_vals[2] += alpha * mask;

                // TEP 3
                let pos = teps[3].positions()[j] as usize;
                let mask = (j < num_pos[3]) as u8 as f32;
                let lp = *log_p.get_unchecked(pos);
                let l1mp = *log_1_minus_p.get_unchecked(pos);
                let alpha = *alpha_mrb.get_unchecked(pos);
                log_pe_vals[3] += (lp - l1mp) * mask;
                debw_vals[3] += alpha * mask;
            }
        }

        // Calculate P(e) = exp(log_pe)
        let pe_vals = Self::exp4(&log_pe_vals);

        let mut p_pro_vals = [0.0; 4];
        if self.promising_probability_model == PromisingProbabilityModel::WeightedNormal {
            for i in 0..4 {
                p_pro_vals[i] = self.calculate_weighted_normal_p_pro(pe_vals[i], debw_vals[i]);
            }
        } else {
            let p = self.parity_p_avg;
            let nmk_f = self.nmk as f32;
            let denom1 = (nmk_f * p * (1.0 - p)).sqrt();
            let denom2 = nmk_f.sqrt();
            let mean_offset = nmk_f * p;
            let mut q_args = ([0.0f32; 4], [0.0f32; 4]);

            for i in 0..4 {
                let beta = ((self.d_min_w - debw_vals[i]) / self.e_p_alpha)
                    .min(nmk_f)
                    .max(0.0);
                q_args.0[i] = (beta + 0.5 - mean_offset) / denom1;
                q_args.1[i] = (2.0 * beta + 1.0 - nmk_f) / denom2;
            }

            let (q1_vals, q2_vals) = Self::q_function_pair_4x(&q_args.0, &q_args.1);
            for i in 0..4 {
                p_pro_vals[i] =
                    pe_vals[i] * (1.0 - q1_vals[i]) + (1.0 - pe_vals[i]) * (1.0 - q2_vals[i]);
            }
        }

        let mut should_process = [false; 4];
        for i in 0..4 {
            if i < valid_count {
                // Check if THIS SPECIFIC TEP is the first one (at global position 0)
                should_process[i] = self.p_pro_t <= 0.0
                    || p_pro_vals[i] > self.p_pro_t
                    || (num_teps_processed as usize + i) == 0;
            } else {
                // Mark dummy TEPs as not to be processed
                should_process[i] = false;
                p_pro_vals[i] = 0.0;
            }
        }

        // Step 4: Generate codewords for TEPs that pass the promising probability test (BATCHED VERSION)
        let mut codewords = [self.baseline_codeword; 4]; // Start with baseline

        for i in 0..4 {
            if should_process[i] {
                // Generate codeword using optimized method
                // codewords[i] = self.generate_codeword_v2_microarch(teps[i]);
                codewords[i] = self.generate_codeword_v2(teps[i]);
            }
        }

        // Step 5: Calculate weighted Hamming distances using vectorized batch F32 lookup
        let distances = if should_process.iter().any(|&x| x) {
            self.batch_weighted_hamming_f32(&codewords, &should_process)
        } else {
            [f32::INFINITY; 4]
        };

        (should_process, distances, codewords, should_process)
    }

    #[inline(always)]
    unsafe fn vectorized_popcount_weight(
        diff_words: &[u64; 3],
        alpha_base: &[f32],
        offsets: &[usize; 3],
    ) -> f32 {
        let mut total_weight = 0.0f32;

        for (word_idx, &diff) in diff_words.iter().enumerate() {
            if diff != 0 {
                let base_offset = offsets[word_idx];

                let mut remaining = diff;
                let mut bit_pos = 0usize;

                while remaining != 0 {
                    let chunk = (remaining & 0xFFFF) as u16;
                    if chunk != 0 {
                        for bit in 0..16 {
                            if (chunk >> bit) & 1 != 0 {
                                total_weight += alpha_base[base_offset + bit_pos + bit];
                            }
                        }
                    }
                    remaining >>= 16;
                    bit_pos += 16;
                }
            }
        }

        total_weight
    }

    /// Generates a codeword by XORing the parity rows selected by the test error pattern.
    pub fn generate_codeword_v2(&self, tep: &TestErrorPattern) -> [u64; 3] {
        // Start with a copy of the baseline codeword.
        let mut cw = self.baseline_codeword; // [u64; 3]

        // This accumulator will hold the XOR–sum of the parity rows corresponding to flipped
        // message bits.
        let mut parity_delta = [0u64; 2];
        let num_positions = tep.num_positions() as usize;

        // For each TEP flip, update the message portion and accumulate parity delta.
        for i in 0..num_positions {
            let pos = tep.positions()[i] as usize;
            // Flip the message bit. (Recall: message bits reside in the first k bits.)
            let word = pos / 64;
            let bit = pos % 64;
            cw[word] ^= 1u64 << bit;
            // Accumulate the parity effect.
            let (word0, word1) = self.parity_row(pos);
            parity_delta[0] ^= word0;
            parity_delta[1] ^= word1;
        }

        // Update the parity portion in the codeword.
        //
        // The message portion occupies:
        //   - All 64 bits of cw[0], and
        //   - The lower (k - 64) bits of cw[1].
        // Thus, the parity portion is in cw[1] (bits (k - 64) to 63) and in cw[2].
        let offset = self.k - 64; // starting bit in cw[1] where parity begins
        let bits_in_word1_parity = 64 - offset; // number of bits in cw[1] used for parity
                                                // Preserve the lower (k - 64) bits (the message part in cw[1]).
        let mask_message = if offset == 64 {
            0
        } else {
            (1u64 << offset) - 1
        };
        let message_part = cw[1] & mask_message;
        // Extract the current parity part from cw[1], update it by XOR–ing parity_delta[0],
        // then merge it back.
        let parity_part =
            (cw[1] >> offset) ^ (parity_delta[0] & ((1u64 << bits_in_word1_parity) - 1));
        cw[1] = message_part | (parity_part << offset);
        // For cw[2], only the lower (N - 128) bits are used (since 2×64 = 128 bits come before).
        let used_bits_word2 = N - 128;
        cw[2] ^= parity_delta[1] & ((1u64 << used_bits_word2) - 1);

        cw
    }

