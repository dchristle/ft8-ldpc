/// Why a PB-OSD TEP search stopped.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum StopReason {
    /// The input already satisfies the code and CRC.
    InitialValid,
    /// The promising-probability criterion stopped traversal.
    PromisingProbability,
    /// The success-probability criterion accepted the incumbent.
    SuccessProbability,
    /// The configured patterns were exhausted.
    Exhausted,
}

