/// Compute n choose k, cancelling the divisor before multiplication.
fn binomial(n: u32, k: u32) -> u32 {
    if k > n {
        return 0;
    }
    let mut value = 1;
    for i in 1..=k.min(n - k) {
        let numerator = n - i + 1;
        let (mut a, mut b) = (numerator, i);
        while b != 0 {
            (a, b) = (b, a % b);
        }
        value = (value / (i / a)) * (numerator / a);
    }
    value
}

