    /// Transpose a matrix stored as Vec<Vec<bool>>
    #[allow(clippy::ptr_arg)]
    fn transpose_matrix(matrix: &Vec<Vec<bool>>, rows: usize, cols: usize) -> Vec<Vec<bool>> {
        let mut transposed = vec![vec![false; rows]; cols];
        for (i, row) in matrix.iter().enumerate() {
            for (j, &value) in row.iter().enumerate() {
                transposed[j][i] = value;
            }
        }
        transposed
    }

    /// Pack a k×N systematic matrix into column-major bit-packed format
    /// Returns array of columns, where each column is represented by two u64s
    #[allow(clippy::ptr_arg)]
    fn pack_systematic_matrix(matrix: &Vec<Vec<bool>>, k: usize) -> [[u64; 2]; 91] {
        let mut packed = [[0u64; 2]; 91];

        // We only need to pack the parity portion (columns k..N)
        // The identity portion is implicit
        for col in k..N {
            let mut bits_low = 0u64; // First 64 bits
            let mut bits_high = 0u64; // Remaining bits

            // Pack first 64 rows
            for row in 0..64.min(N - k) {
                if matrix[row][col] {
                    bits_low |= 1u64 << row;
                }
            }

            // Pack remaining rows
            for row in 64..(N - k) {
                if matrix[row][col] {
                    bits_high |= 1u64 << (row - 64);
                }
            }

            packed[col - k] = [bits_low, bits_high];
        }

        packed
    }

    fn compute_reliability_permutation(alpha: &[f32; N]) -> [usize; N] {
        let mut indices = std::array::from_fn(|index| index);
        indices.sort_unstable_by(|&i, &j| {
            alpha[j]
                .partial_cmp(&alpha[i])
                .unwrap_or(Ordering::Equal)
                .then_with(|| i.cmp(&j))
        });
        indices
    }

    fn encode_systematic_message(
        message: &[bool],
        k: usize,
        parity_rows: &[[u64; 2]; 91],
    ) -> [u64; 3] {
        debug_assert_eq!(message.len(), k);
        let mut codeword = [0u64; 3];
        let mut parity = [0u64; 2];
        for (position, &bit) in message.iter().enumerate() {
            if bit {
                codeword[position / 64] |= 1u64 << (position % 64);
                parity[0] ^= parity_rows[position][0];
                parity[1] ^= parity_rows[position][1];
            }
        }

        let offset = k - 64;
        codeword[1] |= parity[0] << offset;
        codeword[2] = parity[1];
        codeword
    }

    #[inline(always)]
    fn parity_row(&self, position: usize) -> (u64, u64) {
        let row = self.parity_rows[position];
        (row[0], row[1])
    }

    /// Broadcasts Q-function polynomial coefficients for reuse across NEON evaluations.
    #[cfg(target_arch = "aarch64")]
    #[inline(never)]
    fn load_q_coefs() -> (float32x4_t, float32x4_t, float32x4_t) {
        unsafe {
            let a_vec: float32x4_t = vdupq_n_f32(Q_PARAM_A);
            let b_vec: float32x4_t = vdupq_n_f32(Q_PARAM_B);
            let c_vec: float32x4_t = vdupq_n_f32(Q_PARAM_C);
            (a_vec, b_vec, c_vec)
        }
    }

    /// Evaluates exp(C + x * (A * x + B)) for four lanes with preloaded coefficients.
    #[cfg(target_arch = "aarch64")]
    fn q_function_4x_with_coefs(
        coefs: (float32x4_t, float32x4_t, float32x4_t),
        input: &[f32; 4],
    ) -> [f32; 4] {
        let (a_vec, b_vec, c_vec) = coefs;

        unsafe {
            let x_vec: float32x4_t = vld1q_f32(input.as_ptr());

            let axp_b: float32x4_t = vfmaq_f32(b_vec, a_vec, x_vec);

            let poly: float32x4_t = vfmaq_f32(c_vec, x_vec, axp_b);

            let y_vec: float32x4_t = exp4_f32(poly);

            transmute::<float32x4_t, [f32; 4]>(y_vec)
        }
    }

    /// Scalar Q-function approximation for 4 values (non-aarch64 fallback).
    /// Computes y[i] = C + x[i] * (A * x[i] + B), then exp(y[i]).
    #[cfg(not(target_arch = "aarch64"))]
    fn q_function_4x_approx(input: &[f32; 4]) -> [f32; 4] {
        let mut result = [0.0f32; 4];
        for i in 0..4 {
            let x = input[i];
            result[i] = x.mul_add(Q_PARAM_A * x + Q_PARAM_B, Q_PARAM_C).exp();
        }
        result
    }

    /// Vectorized exp for 4 values. Uses NEON on aarch64.
    #[cfg(target_arch = "aarch64")]
    #[inline]
    fn exp4(input: &[f32; 4]) -> [f32; 4] {
        unsafe {
            let x_vec = vld1q_f32(input.as_ptr());
            let y_vec = exp4_f32(x_vec);
            transmute::<float32x4_t, [f32; 4]>(y_vec)
        }
    }

    /// Vectorized exp for 4 values. Scalar fallback for non-aarch64.
    #[cfg(not(target_arch = "aarch64"))]
    #[inline]
    fn exp4(input: &[f32; 4]) -> [f32; 4] {
        [
            input[0].exp(),
            input[1].exp(),
            input[2].exp(),
            input[3].exp(),
        ]
    }

    /// Q-function pair for two sets of four arguments.
    ///
    /// The promising-probability calculation routinely supplies negative
    /// arguments. The Lopez-Benitez polynomial is not valid there, so use the
    /// accurate implementation for every lane.
    #[inline]
    fn q_function_pair_4x(arg1: &[f32; 4], arg2: &[f32; 4]) -> ([f32; 4], [f32; 4]) {
        (q_function_4x(arg1), q_function_4x(arg2))
    }

    /// Calculates d_{e,B}^(W), the weighted Hamming distance of a given Test Error Pattern for
    /// the messages bits portion 'B' (i.e. not including the WHD terms for the parity portion P).
    ///
    /// Computes the sum of bit reliabilities (|LLR| values) for positions specified
    /// in the error pattern. d_{e,B}^(W) is used to calculate the Promising Probability of a
    /// TEP, c.f. equation 7 in the paper.
    ///
    /// # Arguments
    /// * `tep` - Test Error Pattern containing positions to consider
    ///
    /// # Returns
    /// Weighted Hamming distance d_{e,B}^(W) for the messages bits portion 'B'.
    ///
    /// # Safety
    /// Uses `get_unchecked` for performance. All indices in `tep.positions` must be
    /// valid indices within `self.alpha_mrb`.
    #[inline]
    fn calculate_debw(&self, tep: &TestErrorPattern) -> f32 {
        let mut distance = 0.0;
        for i in 0..tep.num_positions() {
            let pos = tep.positions()[i as usize] as usize;
            distance += unsafe { *self.alpha_mrb.get_unchecked(pos) };
        }
        distance
    }

    /// Calculate d_eBW for 4 TEPs at once.
    /// Each TEP has up to 8 positions, so we do a small 8-iteration loop.
    #[inline]
    fn calculate_debw_4(&self, teps: [&TestErrorPattern; 4]) -> [f32; 4] {
        let mut distances = [0.0f32; 4];

        for tep_idx in 0..4 {
            let tep = teps[tep_idx];
            for i in 0..tep.num_positions() {
                let pos = tep.positions()[i as usize] as usize;
                distances[tep_idx] += unsafe { *self.alpha_mrb.get_unchecked(pos) };
            }
        }

        distances
    }

    /// Calculates weighted Hamming distance using precomputed tables.
    #[inline]
    fn calculate_weighted_hamming_efficient(&self, cw: &[bool; N]) -> f32 {
        let mut distance = 0.0;
        for i in 0..N {
            if cw[i] != self.c0_mrb[i] {
                distance += self.alpha_mrb[i];
            }
        }
        distance
    }

    #[cfg(target_arch = "aarch64")]
    #[inline(never)]
    #[no_mangle]
    unsafe fn calculate_debw_simd(&self, tep: &TestErrorPattern) -> f32 {
        use std::arch::aarch64::{vaddvq_f32, vld1q_f32};

        // Fast paths based on position count
        if tep.num_positions() == 0 {
            return 0.0;
        }

        // Prepare for SIMD operations
        let mut values1: [f32; 4] = [0.0; 4];
        let mut values2: [f32; 4] = [0.0; 4];

        // Load values from specified positions
        let count = tep.num_positions() as usize;

        // Load first chunk (0-3)
        let chunk1_count = count.min(4);
        for i in 0..chunk1_count {
            values1[i] = *self.alpha_mrb.get_unchecked(tep.positions()[i] as usize);
        }

        // Load second chunk (4-7) if needed
        if count > 4 {
            for i in 4..count {
                values2[i - 4] = *self.alpha_mrb.get_unchecked(tep.positions()[i] as usize);
            }

            // Load both chunks into SIMD registers and sum
            let v1 = vld1q_f32(values1.as_ptr());
            let v2 = vld1q_f32(values2.as_ptr());

            vaddvq_f32(v1) + vaddvq_f32(v2)
        } else {
            // Only need first chunk
            let v1 = vld1q_f32(values1.as_ptr());
            vaddvq_f32(v1)
        }
    }

    #[cfg(target_arch = "aarch64")]
    #[inline(never)]
    #[no_mangle]
    unsafe fn calculate_debw_full_mask(&self, tep: &TestErrorPattern) -> f32 {
        use std::arch::aarch64::*;

        let count = tep.num_positions() as usize;
        if count == 0 {
            return 0.0;
        }

        // Unconditionally gather all 8 values. For i ≥ count,
        // positions[i] = 0 => alpha_mrb[0] is added.
        let arr = [
            *self.alpha_mrb.get_unchecked(tep.positions()[0] as usize),
            *self.alpha_mrb.get_unchecked(tep.positions()[1] as usize),
            *self.alpha_mrb.get_unchecked(tep.positions()[2] as usize),
            *self.alpha_mrb.get_unchecked(tep.positions()[3] as usize),
            *self.alpha_mrb.get_unchecked(tep.positions()[4] as usize),
            *self.alpha_mrb.get_unchecked(tep.positions()[5] as usize),
            *self.alpha_mrb.get_unchecked(tep.positions()[6] as usize),
            *self.alpha_mrb.get_unchecked(tep.positions()[7] as usize),
        ];

        let values_low = vld1q_f32(arr.as_ptr());
        let sum_low = vaddvq_f32(values_low);

        let mut total = sum_low;

        if count > 4 {
            let values_high = vld1q_f32(arr.as_ptr().add(4));
            let sum_high = vaddvq_f32(values_high);
            // Subtract away any "bogus" alpha_mrb[0] contributions
            // from the invalid lanes (i >= count).
            let correction = (8 - count) as f32 * self.alpha_mrb[0];
            total += sum_high - correction;
            total
        } else {
            total - (4 - count) as f32 * self.alpha_mrb[0]
        }
    }

    // Helper to calculate combination size for pre-allocation
    fn calculate_combination_size(&self, n: u8, r: u8) -> usize {
        let mut res = 1;
        for i in 0..r {
            res = res * (n - i) as usize / (i + 1) as usize;
        }
        res
    }

    /// Calculates the log-probability of a specific Test Error Pattern (TEP) `e`
    /// occurring within the first `k` bits (Most Reliable Basis - MRB).
    ///
    /// Implements Equation 5 from the PB-OSD paper in log-space.
    /// for numerical stability.
    ///
    /// # Paper References
    /// - Eq. 4: `P(i) = (1 + exp(4*gamma*alpha[i]))⁻¹`
    ///     - `P(i)` is the probability that the hard decision for bit `i` (in MRB) is incorrect.
    /// - Eq. 5: `P(e) = Pr(e_B = e) = Product_{i in E} P(i) * Product_{i not in E} (1 - P(i))`
    ///     - `P(e)` is the probability of the specific error pattern `e` occurring in the MRB (first k bits).
    ///     - `E` is the set of bit indices `i` (from 0 to k-1) where the TEP `e` specifies an error (i.e., `e_i = 1`).
    ///     - `NE` is the set of bit indices where `e_i = 0`.
    ///
    /// # Log-Space Calculation
    /// Taking the logarithm of Equation 5:
    /// `log(P(e)) = Sum_{i in E} log(P(i)) + Sum_{i not in E} log(1 - P(i))`
    ///
    /// Start with the sum over all `k` bits assuming no errors,
    /// which is precomputed as `self.sum_log_1_minus_p = Sum_{i=0..k-1} log(1 - P(i))`.
    ///
    /// Then, for each position `pos` where the TEP `e` *does* specify an error (i.e., `pos` is in `E`),
    /// we need to:
    ///   1. Remove the `log(1 - P(pos))` term that was included in the initial sum.
    ///   2. Add the `log(P(pos))` term that should be there according to Eq. 5.
    ///
    /// The adjustment for each error position `pos` is therefore: `log(P(pos)) - log(1 - P(pos))`.
    ///
    /// # Precomputed Values Used
    /// - `self.sum_log_1_minus_p`: Precomputed sum `Sum_{i=0..k-1} log(1 - P(i))`. Assumes `1-P(i)` is the probability of *no* error at bit `i`.
    /// - `self.log_p[i]`: Precomputed value `log(P(i))`. Assumes `P(i)` is the probability of error at bit `i`.
    /// - `self.log_1_minus_p[i]`: Precomputed value `log(1 - P(i))`. Assumes `1-P(i)` is the probability of no error at bit `i`.
    ///
    /// # Arguments
    /// * `tep` - The Test Error Pattern, specifying the positions (0 to k-1) assumed to be in error.
    ///
    /// # Returns
    /// The natural logarithm of the probability `P(e)`.
    #[inline(always)]
    fn calculate_log_pe(&self, tep: &TestErrorPattern) -> f32 {
        // Initialize with the precomputed log-probability of the all-zero error pattern in the MRB.
        // self.sum_log_1_minus_p = Sum_{i=0..k-1} log(1 - P(i)_paper)
        let mut log_p_e = self.sum_log_1_minus_p;

        // Iterate through only the positions specified in the TEP where errors occur (e_i = 1).
        for i in 0..tep.num_positions() as usize {
            // Get the index 'pos' (within 0..k-1) of the current error specified by the TEP.
            let pos = tep.positions()[i] as usize;

            // Fetch the precomputed log-probabilities for this position 'pos'.
            // SAFETY: Accessing via get_unchecked assumes 'pos' is always valid (< k)
            //         and that the TEP construction guarantees this.
            // 'log_p_error_at_pos' should hold log(P(pos)_paper)
            let log_p_error_at_pos = unsafe { *self.log_p.get_unchecked(pos) };
            // 'log_p_correct_at_pos' should hold log(1 - P(pos)_paper)
            let log_p_correct_at_pos = unsafe { *self.log_1_minus_p.get_unchecked(pos) };

            // Apply the adjustment for this error position:
            // Add log(P(pos)) and subtract log(1 - P(pos)).
            log_p_e += log_p_error_at_pos - log_p_correct_at_pos;
        }

        // Final sanity check for NaN/Infinity which could break downstream logic.
        assert!(
            log_p_e.is_finite() && !log_p_e.is_nan(),
            "calculate_log_pe resulted in non-finite value: {log_p_e:.6}"
        );

        log_p_e
    }

