    #[test]
    fn packed_workspace_matches_previous_basis_path_for_every_cascade_level() {
        for tied in [false, true] {
            let alpha: [f32; 174] = std::array::from_fn(|index| {
                if tied {
                    ((index * 7) % 11) as f32
                } else {
                    index as f32 * 0.03125 + (index % 7) as f32 * 0.0001
                }
            });
            let pi1 = FrameDecoder::compute_reliability_permutation(&alpha);
            assert_eq!(pi1, reference_reliability_permutation(&alpha));

            for cascade_bits in 0..=14 {
                let generator = CascadedGeneratorMatrix::new(cascade_bits).unwrap();
                let mut reference = BitMatrix::from_cascaded_generator(&generator);
                reference.to_standard_form();
                let expected = reference.reduce_standard_packed(&pi1);

                let mut workspace = PBOSDBasisWorkspace::from_cascaded_generator(&generator, &pi1);
                let actual = workspace.reduce(&pi1, BasisReductionKernel::Packed);
                assert_eq!(actual, expected, "cascade_bits={cascade_bits}, tied={tied}");

                for row in 0..(91 - cascade_bits) {
                    for col in 0..174 {
                        assert_eq!(
                            workspace.bit(row, col),
                            reference.standard_bit(row, col),
                            "cascade_bits={cascade_bits}, tied={tied}, row={row}, col={col}"
                        );
                    }
                }

                for kernel in [
                    BasisReductionKernel::M4ri4,
                    BasisReductionKernel::M4ri5,
                ] {
                    let mut blocked =
                        PBOSDBasisWorkspace::from_cascaded_generator(&generator, &pi1);
                    assert_eq!(
                        blocked.reduce(&pi1, kernel),
                        expected,
                        "cascade_bits={cascade_bits}, tied={tied}, kernel={kernel:?}"
                    );
                    assert_eq!(
                        blocked.rows, workspace.rows,
                        "cascade_bits={cascade_bits}, tied={tied}, kernel={kernel:?}"
                    );
                }

                let parity_rows = workspace.parity_rows();
                reference.compute_transposed_standard();
                reference.compute_standard_parity_checks();
                reference.compute_parity_matrix();
                for row in 0..(91 - cascade_bits) {
                    assert_eq!(
                        parity_rows[row],
                        [
                            reference.parity_row(row).0,
                            reference.parity_row(row).1
                        ],
                        "cascade_bits={cascade_bits}, tied={tied}, row={row}"
                    );
                }

                let k = 91 - cascade_bits;
                let message: Vec<bool> = (0..k)
                    .map(|position| (position * 11 + cascade_bits) % 7 < 3)
                    .collect();
                let packed = FrameDecoder::encode_systematic_message(&message, k, &parity_rows);
                let encoded = std::array::from_fn(|position| {
                    packed[position / 64] >> (position % 64) & 1 != 0
                });
                assert_eq!(encoded, reference.encode_standard(&message));

                for variant in 0..8 {
                    let candidate = std::array::from_fn(|position| {
                        (position * 13 + variant * 17 + cascade_bits) % 19 < 9
                    });
                    assert_eq!(
                        FrameDecoder::is_systematic_codeword(&candidate, k, &parity_rows),
                        reference.is_standard_codeword(&candidate),
                        "cascade_bits={cascade_bits}, tied={tied}, variant={variant}"
                    );
                }
            }
        }
    }

    #[test]
    fn direct_and_compatibility_constructors_match_both_kernels() {
        for cascade_bits in 0..=14 {
            let k = 91 - cascade_bits;
            let generator = CascadedGeneratorMatrix::new(cascade_bits).unwrap();
            let llrs: [f32; 174] = std::array::from_fn(|index| {
                let magnitude = 0.15 + ((index * 13) % 29) as f32 * 0.08;
                if (index * 17 + cascade_bits) % 5 < 2 {
                    magnitude
                } else {
                    -magnitude
                }
            });
            let alpha = llrs.map(|llr| llr.abs() / 4.0);
            let mut reference_result = None;

            for kernel in [
                BasisReductionKernel::Bitwise,
                BasisReductionKernel::Packed,
                BasisReductionKernel::M4ri4,
                BasisReductionKernel::M4ri5,
            ] {
                let mut compatibility_matrix = BitMatrix::from_cascaded_generator(&generator);
                let mut compatibility = FrameDecoder::new_with_kernel(
                    alpha,
                    1.0,
                    k as u8,
                    &mut compatibility_matrix,
                    llrs,
                    1,
                    kernel,
                );
                let mut direct = FrameDecoder::new_with_cascaded_generator(
                    alpha, 1.0, &generator, llrs, 1, kernel,
                );

                assert_eq!(compatibility.inv_cum_perm, direct.inv_cum_perm);
                assert_eq!(compatibility.c0_mrb, direct.c0_mrb);
                assert_eq!(compatibility.baseline_codeword, direct.baseline_codeword);
                assert_eq!(compatibility.parity_rows, direct.parity_rows);
                for row in 0..k {
                    assert_eq!(
                        compatibility.parity_row(row),
                        direct.parity_row(row),
                        "cascade_bits={cascade_bits}, kernel={kernel:?}, row={row}"
                    );
                }

                for decoder in [&mut compatibility, &mut direct] {
                    decoder.set_diagnostics_enabled(true);
                    decoder.set_search_stats_enabled(true);
                    decoder.set_p_pro_threshold(0.0);
                    decoder.set_p_suc_threshold(f32::INFINITY);
                }
                let compatibility_result = compatibility.decode();
                let direct_result = direct.decode();
                assert_same_result(&compatibility_result, &direct_result);
                if let Some(reference) = &reference_result {
                    assert_same_result(reference, &direct_result);
                } else {
                    reference_result = Some(direct_result);
                }
            }
        }
    }

    #[test]
    fn compatibility_constructor_keeps_caller_matrix_caches_coherent() {
        for cascade_bits in [0, 7, 14] {
            let k = 91 - cascade_bits;
            let generator = CascadedGeneratorMatrix::new(cascade_bits).unwrap();
            let llrs: [f32; 174] = std::array::from_fn(|index| {
                let magnitude = 0.25 + ((index * 17) % 31) as f32 * 0.0625;
                if index % 3 == 0 {
                    magnitude
                } else {
                    -magnitude
                }
            });
            let alpha = llrs.map(|llr| llr.abs() / 4.0);
            let mut matrix = BitMatrix::from_cascaded_generator(&generator);
            let decoder = FrameDecoder::new(alpha, 1.0, k as u8, &mut matrix, llrs, 1);

            let message: Vec<bool> = (0..k)
                .map(|position| (position * 11 + cascade_bits) % 7 < 3)
                .collect();
            let codeword = matrix.encode_standard(&message);

            assert!(matrix.is_standard_codeword(&codeword));
            for row in 0..k {
                assert_eq!(
                    matrix.parity_row(row),
                    decoder.parity_row(row),
                    "cascade_bits={cascade_bits}, row={row}"
                );
            }
            for h_row in 0..(174 - k) {
                let parity = (0..174)
                    .filter(|&column| matrix.parity_check_bit(h_row, column))
                    .fold(false, |value, column| value ^ codeword[column]);
                assert!(!parity, "cascade_bits={cascade_bits}, h_row={h_row}");
            }
        }
    }

    #[test]
    fn rank_deficient_workspace_reduction_is_deterministic() {
        let pi1 = std::array::from_fn(|index| index);
        let mut workspace = PBOSDBasisWorkspace {
            k: 77,
            rows: [[0u64; 3]; 91],
        };
        for row in 0..76 {
            workspace.rows[row][row / 64] = 1u64 << (row % 64);
        }
        workspace.rows[76] = workspace.rows[75];
        let mut packed = PBOSDBasisWorkspace {
            k: workspace.k,
            rows: workspace.rows,
        };
        let legacy_result = workspace.reduce(&pi1, BasisReductionKernel::Bitwise);
        let packed_result = packed.reduce(&pi1, BasisReductionKernel::Packed);

        assert_eq!(legacy_result.0, 76);
        assert_eq!(packed_result, legacy_result);
        assert_eq!(packed.rows, workspace.rows);
        for kernel in [
            BasisReductionKernel::M4ri4,
            BasisReductionKernel::M4ri5,
        ] {
            let mut blocked = PBOSDBasisWorkspace {
                k: 77,
                rows: {
                    let mut rows = [[0u64; 3]; 91];
                    for row in 0..76 {
                        rows[row][row / 64] = 1u64 << (row % 64);
                    }
                    rows[76] = rows[75];
                    rows
                },
            };
            assert_eq!(blocked.reduce(&pi1, kernel), legacy_result);
            assert_eq!(blocked.rows, workspace.rows);
        }
    }

